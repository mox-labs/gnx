"""The collect core: one bounded act of collection, and what it needs around it.

An act fetches one span of one stream from its source, captures it raw, converts, extracts and
normalizes it, and lands it with its checkpoint in one seal; the core plans one act and
answers SQL over what was landed (:class:`Collection`, its driving port). It knows no act but
the one it runs and never imports ``recon.observe``.

The names below are the core's public API: what the observe layer, and any outside driver
(a harness, a flow, a later observe package), may use. ``recon.observe`` imports nothing of
the core but these (``tests/test_layering.py`` holds both rules).
"""


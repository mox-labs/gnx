def test_the_exit_code_table_is_the_code_s() -> None:
    for kind, code in recon.EXIT_CODES.items():
        row = f"| {code} | `{kind}` | {recon.EXIT_MEANINGS[kind]} | {recon.EXIT_NEXT[kind]} |"
        assert row in SKILL, kind
    rows = re.findall(r"^\| (\d+) \| `(\w+)` \|", SKILL, flags=re.M)
    assert {kind: int(code) for code, kind in rows} == recon.EXIT_CODES


def test_the_kinds_and_schemas_listed_are_the_code_s() -> None:
    assert "`error.kind` is one of " + ", ".join(f"`{k}`" for k in recon.ERROR_KINDS) in SKILL
    assert (
        "A problem's `kind` is one of " + ", ".join(f"`{k}`" for k in recon.PROBLEM_KINDS) in SKILL
    )
    for schema in ("plan", "survey", "status", "query-rows", "templates", "mission", "capture",
                   "error", "event"):  # fmt: skip
        assert f"`recon.v1.{schema}`" in SKILL


def test_the_error_envelope_shown_is_the_one_printed(tmp_path: Path, monkeypatch: Any) -> None:
    envelope = '{"schema": "recon.v1.error"'
    [shown] = [line for line in SKILL.splitlines() if line.startswith(envelope)]
    (tmp_path / ".git").mkdir()
    monkeypatch.chdir(tmp_path)
    config = tmp_path / ".recon" / "m" / "config.yaml"
    config.parent.mkdir(parents=True)
    config.write_text(yaml.safe_dump({"collectors": [{"name": "a", "type": "ftp"}]}))
    result = _invoke("survey", "m", "--dry-run", "--json")
    assert result.exit_code == 3
    printed = json.loads(result.stderr.replace(str(config), "<file>"))
    assert printed == json.loads(shown)


def test_every_command_and_flag_named_exists() -> None:
    commands = set(main.commands)
    code = "\n".join(body for _, body in _blocks(SKILL))
    invocations = re.findall(r"`(recon [^`]*)`", SKILL) + re.findall(r"^(recon .*)$", code,
                                                                       flags=re.M)  # fmt: skip
    named = {word for words in invocations if not (word := words.split()[1]).startswith(("-", "<"))}
    assert named and named <= commands, named - commands
    flags = {opt for cmd in [main, *main.commands.values()] for p in cmd.params for opt in p.opts}
    used = {flag for words in invocations for flag in re.findall(r"(?<![\w-])(--?[a-z][a-z-]*)",
                                                                 words)}  # fmt: skip
    assert used and used <= flags | {"--help", "-h"}, used - flags


def test_every_mission_shown_plans_clean_in_this_build() -> None:
    plugins = composition.load_plugins()
    texts = {"SKILL.md": SKILL} | REFERENCES
    shown = [(name, mission) for name, text in texts.items() for mission in _missions(text)]
    assert len(shown) >= 15, "the scan found the missions"
    for name, mission in shown:
        plan = build_plan(mission, plugins, {})
        assert plan.valid, (name, mission["collectors"][0]["name"], plan.problems)


def _page_catalog(text: str) -> list[dict[str, Any]]:
    """The sources a page shows, in a ``catalog:`` block or as a block of source entries
    alone (a walkthrough that adds one source at a time); a source shown again is its last
    showing."""
    sources: list[dict[str, Any]] = []
    for block in _yaml_blocks(text):
        try:
            parsed = yaml.safe_load(block)
        except yaml.YAMLError:
            continue  # a fragment of a mapping, shown indented under its key
        if isinstance(parsed, dict) and isinstance(parsed.get("catalog"), list):
            sources += parsed["catalog"]
        elif isinstance(parsed, list) and all(
            isinstance(i, dict) and ("url" in i or "command" in i) for i in parsed
        ):
            sources += parsed
    return list({source.get("name"): source for source in sources}.values())


def test_every_mission_the_docs_and_readme_show_plans_clean_in_this_build() -> None:
    """The how-tos, the explanation and the README show missions too; a reader copies them
    as the skill's are copied, so each must plan in this build. A ``collectors:`` block with
    no ``catalog:`` of its own runs against the sources its page showed."""
    plugins = composition.load_plugins()
    pages = [PACKAGE / "README.md", *sorted((PACKAGE / "docs").glob("*/*.md"))]
    shown = []
    for page in pages:
        # The record holds no missions; extending.md's mission uses the plugin type it builds.
        if "design" in page.parts or page.name == "extending.md":
            continue
        text = page.read_text()
        catalog = _page_catalog(text)
        shown += [
            (page.relative_to(PACKAGE), {"catalog": catalog, **mission})
            for mission in _missions(text)
        ]
    assert shown, "the scan found the missions"
    for page, mission in shown:
        plan = build_plan(mission, plugins, {})
        assert plan.valid, (str(page), mission["collectors"][0]["name"], plan.problems)


def test_no_pointer_to_a_file_the_command_cannot_print() -> None:
    for name, text in ({"SKILL.md": SKILL} | REFERENCES).items():
        assert not re.search(r"\]\((?!https?:|#)[^)]+\)", text), f"{name}: a relative link"
        for phrase in ("orders of magnitude", "until that command lands"):
            assert phrase not in text, (name, phrase)
        assert not re.search(r"(?<![/\w])(docs|examples)/", text), (name, "a package path")
    for reference in re.findall(r"recon --skill -r ([\w-]+)", SKILL):
        assert reference in REFERENCES


def test_the_minimal_example_runs(tmp_path: Path, monkeypatch: Any) -> None:
    """The example as written: a git repository, the mission file, the four commands."""
    for args in (["init", "-q"], ["-c", "user.email=t@t", "-c", "user.name=t", "commit",
                                  "--allow-empty", "-q", "-m", "first"]):  # fmt: skip
        subprocess.run(["git", *args], cwd=tmp_path, check=True)
    monkeypatch.chdir(tmp_path)
    [mission] = _missions(SKILL.split("## Minimal example")[1].split("\n## ")[0])
    (tmp_path / "mission.yaml").write_text(yaml.safe_dump(mission))
    section = SKILL.split("## Minimal example")[1].split("\n## ")[0]
    [block] = [body for language, body in _blocks(section) if language == ""]
    commands = [line.split() for line in block.splitlines() if line.startswith("recon ")]
    assert len(commands) == 4
    results = []
    for words in commands:
        args = words[1:]
        if args[0] == "query":  # the SQL is one argument, as the shell would pass it
            args = ["query", args[1], " ".join(args[2:-1]).strip('"'), args[-1]]
        results.append(_invoke(*args))
        assert results[-1].exit_code == 0, (words, results[-1].stderr)
    rows = json.loads(results[-1].stdout)["rows"]
    assert rows and rows[0]["line"].endswith("first")



"""The ``--skill`` text is a contract an agent acts on, so these tests keep it true to the code:
the frontmatter, the length budget, the exit-code table, the error envelope, the commands
and flags it names, and every mission it shows, which must plan clean in this build. The
minimal example is run for real.
"""

from __future__ import annotations

import importlib.util
import json
import re
import subprocess
from pathlib import Path
from typing import Any

import pytest
import yaml
from click.testing import CliRunner

import recon
from recon import composition
from recon.adapters._in.cli import main
from recon.application.plan import build_plan

SKILL = recon.skill()
REFERENCES = {name: recon.skill(name) for name in recon.skill_references()}
PACKAGE = Path(__file__).resolve().parents[1]
REPO = PACKAGE.parents[2]

#: The top-level keys a skill's frontmatter may have and still upload (Claude Code docs).
PORTABLE_KEYS = {"name", "description", "license", "compatibility", "metadata", "allowed-tools"}

#: What must sit in the first 5,000 tokens, which Claude Code keeps of a skill after
#: compaction: the purpose, when not to use it, the prerequisites, the minimal example, the
#: commands in order, and the errors.
FRONT_SECTIONS = (
    "## When to use it, and when not",
    "## Prerequisites",
    "## Minimal example",
    "## The loop",
    "## Errors and exit codes",
)

#: Characters per token, for the budget. An estimate (English prose runs at about four);
#: the margin it leaves is checked, not the exact count.
CHARS_PER_TOKEN = 4


def _invoke(*args: str, stdin: str | None = None) -> Any:
    return CliRunner().invoke(main, list(args), input=stdin, catch_exceptions=False)


def _frontmatter(text: str) -> tuple[dict[str, Any], str]:
    assert text.startswith("---\n"), "the printed text begins with frontmatter"
    head, _, body = text[4:].partition("\n---\n")
    return yaml.safe_load(head), body


def _blocks(text: str) -> list[tuple[str, str]]:
    """Every fenced block, as (language, body); a block indented under a list item is read
    without its indent."""
    blocks: list[tuple[str, str]] = []
    language: str | None = None
    lines: list[str] = []
    indent = 0
    for line in text.splitlines():
        fence = line.lstrip().startswith("```")
        if fence and language is None:
            indent = len(line) - len(line.lstrip())
            language, lines = line.lstrip()[3:].strip(), []
        elif fence:
            blocks.append((language or "", "\n".join(lines) + "\n"))
            language = None
        elif language is not None:
            lines.append(line[indent:])
    return blocks


def _yaml_blocks(text: str) -> list[str]:
    return [body for language, body in _blocks(text) if language == "yaml"]


#: The first line of a YAML block that shows the mission file's keys rather than a mission.
SCHEMA_MARKER = "# Every key a mission file can hold"


def _missions(text: str) -> list[dict[str, Any]]:
    """Every YAML block that is a whole mission (a mapping with ``collectors:``)."""
    blocks = [
        yaml.safe_load(block) for block in _yaml_blocks(text) if not block.startswith(SCHEMA_MARKER)
    ]
    return [b for b in blocks if isinstance(b, dict) and "collectors" in b]



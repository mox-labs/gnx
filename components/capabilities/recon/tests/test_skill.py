@pytest.fixture
def surveyed(tmp_path: Path, monkeypatch: Any) -> Path:
    """A project whose mission ``m`` has two archives, each with a ``papers`` table."""
    (tmp_path / ".git").mkdir()
    monkeypatch.chdir(tmp_path)
    papers = [{"title": "p", "authors": ["a", "b"]}, {"title": "q", "authors": ["a"]}]
    run = "; ".join(f"echo '{json.dumps(paper)}'" for paper in papers)
    config = tmp_path / ".recon" / "m" / "config.yaml"
    config.parent.mkdir(parents=True)
    config.write_text(
        yaml.safe_dump({"collectors": [{"name": "papers", "type": "cli", "run": run}]})
    )
    for _ in range(2):
        assert _invoke("survey", "m").exit_code == 0
    return tmp_path


def _walk(document: Any, path: str) -> Any:
    """``missions[0].latest.path`` in ``document``."""
    for key, index in re.findall(r"(\w+)(?:\[(\d+)\])?", path):
        document = document[key]
        if index:
            document = document[int(index)]
    return document


def test_the_archive_listing_is_where_the_skill_says(surveyed: Path) -> None:
    """Regression: the skill said `recon status <name> --json` lists the archives as
    `history`; they are under `missions[0]`. The path and the fields are read from the skill
    and walked in what the command prints."""
    [(path, fields)] = re.findall(
        r"`recon status <name> --json` lists every archive of that mission, oldest first, as "
        r"`([^`]+)`: each archive's ((?:`\w+`(?:, | and )?)+)",
        SKILL,
    )
    status = json.loads(_invoke("status", "m", "--json").stdout)

    history = _walk(status, path)
    assert len(history) == 2 and history[0]["id"] < history[1]["id"], "oldest first"
    for field in re.findall(r"`(\w+)`", fields):
        assert all(archive[field] is not None for archive in history), field


def test_the_row_citation_recipe_cites_the_line(surveyed: Path) -> None:
    """Regression: the recipe read a glob across archives, which failed when their columns
    differed. It reads one archive's file, by the path the skill says where to find."""
    [where] = re.findall(
        r"Take the archive's `path` from `recon status <name> --json` \(`([^`]+)`", SKILL
    )
    [sql] = re.findall(r"then `(SELECT ordinality AS line, [^`]+)`", SKILL)
    archive = _walk(json.loads(_invoke("status", "m", "--json").stdout), where)
    sql = sql.replace("<path>", archive).replace("<table>", "papers") + " WHERE title = 'q'"

    [row] = json.loads(_invoke("query", "m", sql, "--json").stdout)["rows"]

    line = Path(archive, "papers.jsonl").read_text().splitlines()[row["line"] - 1]
    assert json.loads(line)["title"] == row["title"] == "q"


def test_the_count_over_a_list_runs(surveyed: Path) -> None:
    [sql] = re.findall(r"`(SELECT author, count\(\*\) AS n FROM \(SELECT unnest[^`]+)`", SKILL)
    rows = json.loads(_invoke("query", "m", sql, "--json").stdout)["rows"]
    assert rows == [{"author": "a", "n": 2}, {"author": "b", "n": 1}]


def _taught_sql() -> list[str]:
    """Every query the skill and its references show: each ```sql block, each `recon query`
    argument, and each inline `SELECT ...`."""
    found = []
    for text in [SKILL, *REFERENCES.values()]:
        found += re.findall(r"```sql\n(.*?)```", text, re.DOTALL)
        found += re.findall(r'recon query \S+ "([^"]+)"', text)
        found += re.findall(r"`(SELECT [^`]+)`", text)
    return found


def test_no_query_the_skill_teaches_is_refused_as_a_write(tmp_path: Path) -> None:
    """recon query runs SELECT statements only; nothing the skill teaches may be refused for
    that. A taught query may name a table this archive lacks, which is a different error."""
    from recon.adapters._out.archive_files import ArchiveFiles
    from recon.adapters._out.duckdb_query import DuckdbQuery
    from recon.adapters._out.system_clock import SystemClock

    store = ArchiveFiles(SystemClock())
    archive = store.create(tmp_path / "m", "2026-01-01-000000-000000")
    store.write_table(archive, "papers", (r for r in [{"title": "q", "authors": ["a"]}]))
    taught = _taught_sql()
    assert len(taught) > 10, taught
    for sql in taught:
        try:
            DuckdbQuery(store).execute(archive, sql)
        except recon.QueryError as error:
            assert "statements" not in error.details, sql
